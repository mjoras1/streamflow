"""### Part 1a - Shear Diagram

You will create your shear diagram in the code block below.

"""

#Used AI to understand the instructions and to help plot the code and annotations
# Define variables
L = 6
q1 = 170
q2 = 410
P1 = 100
RA = 120
RB = 120

# Define x and V
x = np.linspace(0, L, 500)
V = np.zeros_like(x)

# Calculate shear
for i in range(len(x)):
    if x[i] < 2:
        V[i] = RA - (q1 * x[i])

    elif x[i] < 4:
        V[i] = RA - (q1 * 2) - P1

    else:
        V[i] = RA - (q1 * 2) - P1 + RB - (q2 * (x[i] - 4))

# Plot shear diagram
plt.figure(figsize=(12, 6))
plt.plot(x, V, label='Shear Force', color='blue', linewidth=2)

plt.axhline(y=0, color='black', linewidth=1)
plt.axvline(x=2, color='gray', linestyle='--')
plt.axvline(x=4, color='gray', linestyle='--')

plt.xlabel('Distance (m)')
plt.ylabel('Shear Force')
plt.title('Shear Force Diagram')
plt.grid(True)
plt.legend()
plt.xlim(0, L)

plt.show()

"""### Part 1b - Moment Diagram

You will create your moment diagram in the code block below.
"""

#Used AI to understand the instructions and to help plot the code and annotations
# Define variables
L = 6
q1 = 170
q2 = 410
P1 = 100
RA = 120
RB = 120

# Define x and M
x = np.linspace(0, L, 500)
M = np.zeros_like(x)

# Calculate moment
for i in range(len(x)):
    if x[i] < 2:
        M[i] = (RA * x[i]) - (q1 * (x[i]**2 / 2))

    elif x[i] < 4:
        M[i] = (RA * x[i]) - (q1 * 2 * (x[i] - 1)) - (P1 * (x[i] - 2))

    else:
        M[i] = (RA * x[i]) - (q1 * 2 * (x[i] - 1)) - (P1 * (x[i] - 2)) + (RB * (x[i] - 4)) - (q2 * (x[i] - 4) * ((x[i] - 4) / 2))

# Plot moment diagram
plt.figure(figsize=(12, 6))
plt.plot(x, M, label='Bending Moment', color='red', linewidth=2)

plt.axhline(y=0, color='black', linewidth=1)
plt.axvline(x=2, color='gray', linestyle='--')
plt.axvline(x=4, color='gray', linestyle='--')

plt.xlabel('Distance (m)')
plt.ylabel('Bending Moment')
plt.title('Bending Moment Diagram')
plt.grid(True)
plt.legend()
plt.xlim(0, L)

plt.show()

